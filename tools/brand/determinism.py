"""Regenerate twice with the existing isolated rasterizer; compare actual bytes."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser()
parser.add_argument('--modules', required=True)
args = parser.parse_args()
ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / 'docs/brand'


def sha(file):
    return hashlib.sha256(file.read_bytes()).hexdigest()


runs = []
for _ in range(2):
    subprocess.run(['node', 'tools/brand/build.mjs', '--modules', args.modules], cwd=ROOT, check=True)
    evidence = json.loads((BRAND / 'evidence/exports.json').read_text(encoding='utf-8'))
    hashes = {entry['file']: sha(BRAND / entry['file']) for entry in evidence['files']}
    assert hashes == {entry['file']: entry['sha256'] for entry in evidence['files']}
    hashes['evidence/exports.json'] = sha(BRAND / 'evidence/exports.json')
    runs.append(hashes)
assert runs[0] == runs[1], 'Generated bytes changed between repeated builds'
report = {
    'result': 'PASS', 'reruns': 2,
    'scope': 'Same machine, pinned resvg 2.6.2. Logo exports are font-free; proof labels depend on local Segoe UI.',
    'generatorSHA256': sha(ROOT / 'tools/brand/build.mjs'),
    'verifierSHA256': sha(Path(__file__)),
    'rasterizer': evidence['rasterizer'],
    'node': subprocess.check_output(['node', '--version'], text=True).strip(),
    'files': runs[1],
}
(BRAND / 'evidence/determinism.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8', newline='\n')
print(f'PASS: two reruns produced identical hashes for {len(runs[1])} generated files.')
