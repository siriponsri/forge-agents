import {readFile,writeFile,copyFile,mkdir} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {bytesDigest} from '../../app/guarded-runtime/profile.mjs';
const [source,bun]=process.argv.slice(2);
if(!path.isAbsolute(source??'')||!path.isAbsolute(bun??''))throw Error('ABSOLUTE_ISOLATED_PATHS_REQUIRED');
const cache=path.dirname(source),home=path.join(cache,'fixture-home');await mkdir(home,{recursive:true});
const fixture=path.join(source,'packages/core/forge-guarded-fixture.ts');
await copyFile(fileURLToPath(new URL('./native-fixture.ts',import.meta.url)),fixture);
const env={SystemRoot:process.env.SystemRoot,TEMP:process.env.TEMP,TMP:process.env.TEMP,PATH:path.dirname(bun),HOME:home,USERPROFILE:home,APPDATA:home,LOCALAPPDATA:home,XDG_CONFIG_HOME:home,XDG_DATA_HOME:home,XDG_CACHE_HOME:home,OPENCODE_DISABLE_AUTOUPDATE:'1',OPENCODE_DISABLE_MODELS_FETCH:'1',OPENCODE_CONFIG_PROJECT_DISABLE:'1',OPENCODE_DISABLE_PROJECT_CONFIG:'1'};
const out=path.join(cache,'native-fixture'),bundle=path.join(out,'forge-guarded-fixture.js');
const build=spawnSync(bun,['build',fixture,'--target=bun',`--outdir=${out}`],{cwd:source,env,encoding:'utf8',windowsHide:true,timeout:120000});
console.log(build.stdout,build.stderr);
if(build.status!==0)throw Error('NATIVE_FIXTURE_BUILD_FAILED');
const run=spawnSync(bun,[fixture],{cwd:home,env,encoding:'utf8',windowsHide:true,timeout:60000});
console.log(run.stdout,run.stderr);
const bundleRun=spawnSync(bun,[bundle],{cwd:home,env,encoding:'utf8',windowsHide:true,timeout:60000});
console.log(bundleRun.stdout,bundleRun.stderr);
const report={version:1,scope:'actual patched native module fixture only, no provider/model turn or full CLI qualification',bundleSha256:bytesDigest(await readFile(bundle)),fixtureSha256:bytesDigest(await readFile(fixture)),buildExit:build.status,runExit:run.status,bundleRunExit:bundleRun.status,stdout:run.stdout,proof:null};
await writeFile(path.join(cache,'native-fixture-report.json'),JSON.stringify(report,null,2)+'\n');
if(run.status!==0||bundleRun.status!==0)throw Error('NATIVE_FIXTURE_FAILED');
