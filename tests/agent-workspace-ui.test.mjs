import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, mkdir, writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {chromium} from 'playwright';
import {createApplication} from '../app/server/main.mjs';
import {entity} from '../app/server/domain.mjs';

test('built Chat transforms into a scoped graph and reuses guarded run controls without dispatch on view changes', async context => {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'forge-agent-workspace-'));
  const app = await createApplication({dataDir: path.join(directory, 'state'), machineSecretDir: path.join(directory, 'vault'), port: 0});
  context.after(() => app.close());
  const browser = await chromium.launch({headless: true, ...(process.env.FORGE_TEST_BROWSER ? {executablePath: process.env.FORGE_TEST_BROWSER} : {})});
  context.after(() => browser.close());
  const page = await browser.newPage({viewport: {width: 1600, height: 1100}}), errors = [], writes = [];
  const nav = async name => {
    const navigation = page.locator('.sidebar nav');
    if (!await navigation.isVisible()) await page.getByRole('button', {name: 'Menu', exact: true}).click();
    const route = navigation.getByRole('button', {name, exact: true, includeHidden: true});
    const group = route.locator('xpath=ancestor::details[1]');
    if (await group.count() && !await group.evaluate(element => element.open)) await group.locator('summary').click();
    await route.click();
  };
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {if (request.method() === 'POST') writes.push(new URL(request.url()).pathname);});
  const bootstrap = await page.request.get(app.url + '/api/session');
  const csrf = (await bootstrap.json()).csrf;
  const post = async (route, input) => {
    const response = await page.request.post(app.url + route, {headers: {'X-Forge-CSRF': csrf}, data: input});
    const data = await response.json(); assert.equal(response.ok(), true, JSON.stringify(data)); return data;
  };
  const create = async (type, projectId, data) => (await post('/api/command', {type, projectId, data, operationId: crypto.randomUUID()})).entity;
  const project = await create('project.create', null, {name: 'Graph engineering fixture', workspace: path.join(directory, 'workspace')});
  const executor = await create('bot.create', project.id, {name: 'Executor · fixture', role: 'Implement the approved software task', kind: 'resident'});
  const reviewer = await create('bot.create', project.id, {name: 'Reviewer · fixture', role: 'Review actual evidence', kind: 'resident'});
  const room = await create('conversation.create', project.id, {name: 'Software mission · fixture', kind: 'team'});
  const empty = await create('conversation.create', project.id, {name: 'Empty fixture room', kind: 'team'});
  await mkdir(project.workspace, {recursive: true});
  const artifact = await post('/api/artifacts/upload', {operationId: crypto.randomUUID(), projectId: project.id, name: 'verified-notes-fixture.txt', kind: 'file', base64: Buffer.from('Actual disposable engineering file bytes. No software product was built.').toString('base64')});
  let runId;
  await app.store.transaction(state => {
    const record = entity({kind: 'conversation', conversationId: room.id, botId: executor.id, attemptId: crypto.randomUUID(), operationId: crypto.randomUUID(), status: 'running', selection: {instanceId: 'fixture', model: 'Injected observation — no model call', options: []}, connection: {status: 'connected'}, toolObservations: {read: {id: 'read', name: 'read source · fixture', status: 'running', resultObserved: false}}, messages: []}, project.id);
    runId = record.id; record.artifactIds = [artifact.id]; state.runs.push(record);
    state.runs.push(entity({kind: 'conversation', conversationId: room.id, botId: reviewer.id, parentRunId: record.id, attemptId: crypto.randomUUID(), operationId: crypto.randomUUID(), status: 'running', connection: {status: 'connected'}, selection: {model: 'Recorded reviewer fixture'}, messages: []}, project.id));
  });
  await page.goto(app.url);
  await page.getByLabel('Language').selectOption('en');
  await nav('Conversations');
  await page.getByRole('button', {name: /Software mission · fixture/}).click();
  await page.getByLabel('Message', {exact: true}).fill('Unsaved conversation draft');
  await page.getByRole('button', {name: 'Workspace', exact: true}).click();
  await page.getByRole('region', {name: 'Visualization Workspace', exact: true}).waitFor();
  assert.equal(await page.locator('.edge-execution.edge-active').first().evaluate(element=>getComputedStyle(element).strokeDasharray), 'none');
  assert.equal(await page.locator('.edge-delegation.edge-active').evaluate(element=>getComputedStyle(element).strokeDasharray), '9px, 4px');
  await page.getByRole('button', {name: /Called agent · Executor/}).click();
  await page.getByRole('button', {name: 'Request stop', exact: true}).waitFor();
  await page.getByRole('button', {name: 'Read recovery snapshot', exact: true}).click();
  await page.getByText('Persisted recovery snapshot', {exact: true}).waitFor();
  await page.getByRole('button', {name: /Called agent · Reviewer/}).click();
  assert.equal(await page.getByText('Persisted recovery snapshot', {exact: true}).count(), 0);
  await page.getByRole('button', {name: /Called agent · Executor/}).click();
  assert.equal(await page.locator('.agent-node').count(), 7);
  await page.getByRole('button', {name: /Artifact · verified-notes-fixture.txt/}).click();
  await page.getByText(/Artifact referenced by run ·/).waitFor();
  assert.equal((await page.request.get(app.url + `/api/artifacts/${artifact.id}/download`)).ok(), true);
  await app.store.transaction(state => {
    const record = state.runs.find(run => run.id === runId);
    record.status = 'unknown'; record.connection.status = 'disconnected';
    record.toolObservations.read = {...record.toolObservations.read, status: 'completed', argumentsComplete: true, resultObserved: false};
    record.toolObservations.edit = {id:'edit',name:'file_change',observationKind:'file_change',path:'allowed/a.txt',status:'completed',argumentsComplete:false,resultObserved:false};
    record.revision++;
    const child = state.runs.find(run => run.parentRunId === runId); child.status = 'completed'; child.connection.status = 'disconnected'; child.revision++;
  });
  await page.getByRole('button', {name: /Tool · read source · fixture · Outcome unconfirmed/}).waitFor();
  await page.getByRole('button', {name: /Tool · read source · fixture/}).click();
  await page.getByText('Tool call observed; its result has not been confirmed.', {exact: true}).waitFor();
  await page.getByRole('button',{name:/Tool · File change: allowed\/a.txt/}).click();
  await page.getByText('Native provider file change observed; this is not a tool result.',{exact:true}).waitFor();
  await page.getByText('File change: allowed/a.txt',{exact:true}).first().waitFor();
  await page.getByRole('button', {name: 'Zoom out', exact: true}).click();
  await page.getByRole('button', {name: 'Fit readable', exact: true}).click();
  await page.getByRole('button', {name: 'Show list', exact: true}).click();
  await page.locator('.agent-node-list').waitFor();
  await page.getByRole('button', {name: 'Show graph', exact: true}).click();
  await page.getByRole('button', {name: 'Chat', exact: true}).click();
  assert.equal(await page.getByLabel('Message', {exact: true}).inputValue(), 'Unsaved conversation draft');
  await page.getByRole('button', {name: 'Workspace', exact: true}).click();
  const captureDir = path.join(directory,'captures'); await mkdir(captureDir, {recursive: true});
  for (const [theme, width, name] of [['dark-modern', 1600, 'desktop'], ['light-modern', 768, 'tablet'], ['dark-modern', 375, 'mobile']]) {
    await page.evaluate(theme => {document.documentElement.dataset.theme = theme;}, theme);
    await page.setViewportSize({width, height: 1100});
    const closeDetails = page.getByRole('button', {name: 'Close graph details', exact: true});
    if (await closeDetails.isVisible()) await closeDetails.click();
    await page.getByRole('button', {name: 'Fit readable', exact: true}).click();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1); assert.equal(overflow, false, `Page overflow at ${width}`);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({path: path.join(captureDir, name + '.png'), fullPage: true, animations: 'disabled'});
  }
  await page.emulateMedia({reducedMotion: 'reduce'});
  await page.getByLabel('Language').selectOption('th');
  await page.getByRole('button', {name: 'ดูรายการ', exact: true}).click();
  await page.getByRole('button', {name: /สมาชิกที่ถูกเรียก · Executor/}).focus();
  await page.keyboard.press('Enter');
  await page.getByRole('button', {name: 'ขอหยุด', exact: true}).waitFor();
  await page.getByRole('button', {name: /Empty fixture room/}).click();
  await page.getByRole('heading', {name: 'บทสนทนาจะกลายเป็นภาพการทำงานที่นี่', exact: true}).waitFor();
  assert.deepEqual(writes.filter(route => /runs\/.*\/(stop|approval|reconcile)|conversations\/send|runs\/start/.test(route)), []);
  assert.deepEqual(errors, []);
  await writeFile(path.join(captureDir, 'evidence.json'), JSON.stringify({qualification: 'PRODUCTION_APP_REAL_SQLITE_INJECTED_RUN_OBSERVATIONS', directory, captures: ['desktop', 'tablet', 'mobile'], errors, noExecutionOnViewChange: true, providerCalls: 0}, null, 2));
  assert.ok(empty.id);
});
